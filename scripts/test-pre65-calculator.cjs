const assert = require('node:assert/strict');
const {calculate,contributionRate} = require('../pre65/calculator.js');
const base = {region:'us',hh:2,wages:0,se:0,trad:86000,roth:0,ss:0,pen:0,inv:0,other:0,hsa:0,hsaRoom:null,ded:0,bench:2100,enroll:null,months:12};
const near=(actual,expected)=>assert.ok(Math.abs(actual-expected)<0.000001,`${actual} != ${expected}`);
near(calculate(base).credit,16410.8);
near(calculate({...base,trad:86560}).rate,0.1022);
assert.equal(calculate({...base,trad:86561}).credit,null);
near(calculate({...base,months:6}).credit,8205.4);
near(calculate({...base,enroll:500}).credit,6000);
assert.equal(calculate({...base,hsa:1000}).hsaUnconfirmed,true);
assert.equal(calculate({...base,hsa:1000,hsaRoom:999}).credit,null);
assert.equal(calculate({...base,hsa:1000,hsaRoom:1000}).hsaUnconfirmed,false);
assert.equal(calculate({...base,trad:97000,hsa:11000,hsaRoom:11000}).magi,86000);
assert.equal(calculate({...base,trad:25000}).credit,null);
assert.equal(calculate({...base,region:'ak',hh:2}).cliff,108200);
assert.equal(calculate({...base,region:'hi',hh:2}).cliff,99560);
assert.equal(calculate({...base,se:-1000,other:2000,inv:-500}).magi,86500);
near(contributionRate(100),.0215); near(contributionRate(133),.0323);
near(contributionRate(150),.043); near(contributionRate(200),.0678);
near(contributionRate(250),.0866); near(contributionRate(300),.1022);
near(contributionRate(175),.0554);
assert.equal(contributionRate(400.001),null);
console.log('Passed 20 calculator checks: income bands, exact cliff, HSA validation, partial-year credit, premium cap and regional FPL.');
